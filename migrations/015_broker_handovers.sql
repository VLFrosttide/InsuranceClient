-- Migration: Broker hand-over to the owner (payment that never reaches a branch)
-- Description: A broker sometimes pays the OWNER directly, in the office, so the
--              money never reaches a branch's drawer. Until now the only way to
--              record it was a broker balance "Increase", which also marks the
--              money as that branch's Cash from Brokers - money the branch is
--              then expected to hold, although it never arrived.
--
--              Such a payment is now its own movement on the broker's ledger:
--
--                Type   = 'handover'     (instead of 'increase')
--                Branch = NULL           (no branch took the money)
--
--              What it does:
--                * raises the broker's CashBalance exactly like a top-up, so the
--                  broker's debt shrinks and the website shows the new balance;
--                * is read as a PAYMENT by the reports
--                  (GET /reports/cash-inflow sums 'increase' and 'handover')
--                  and by the broker's "last payment" date;
--                * writes NO row to cash_transactions or
--                  total_cash_transactions;
--                * is NEVER counted in a branch's Cash from Brokers:
--                  Requests/CurrentCash.js sums only Type = 'increase' rows that
--                  carry a Branch, so a hand-over is excluded by both its type
--                  and its missing branch.
--
--              No schema change: hand-overs live in `broker_balance_movements`
--              (Type/Amount/Reason/Author/Currency/CreatedAt already exist), so
--              the broker's history, corrections, deletions and restores keep
--              working unchanged. The currency is stored even though there is no
--              branch, so reports can show what the owner collected in.
--
--              A hand-over cannot be corrected into an 'increase'/'reduce' (or
--              the other way round): that would move the money between the
--              broker's balance and Cash from Brokers. Delete the wrong row and
--              record the right one instead.
